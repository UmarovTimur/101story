export interface Story {
  /** Стабильный id истории, напр. "uz85" */
  id: string;
  /** Порядковый номер истории */
  number: number;
  /** Заголовок */
  title: string;
  /** Ссылка на место в Библии, напр. "Luqo ... 22-bob" */
  reference: string;
  /** Текст истории, разбитый на абзацы */
  paragraphs: string[];
  /** Вопросы для размышления */
  questions: string[];
  /** Имя аудиофайла в /public/audio/<lang>/ */
  audio: string;
  /** Имя исходной картинки в assets/images/ (общая для всех языков) */
  image: string;
}

export interface Language {
  /** ISO 639 код языка, напр. "uz" — он же сегмент URL и имя папки с аудио */
  code: string;
  /**
   * BCP-47 тег для lang/hreflang, если он отличается от code
   * (напр. "ug-Cyrl": уйгурский здесь в кириллице, а не в арабском письме).
   */
  hreflang?: string;
  /** Название на самом языке */
  name: string;
  /** Название по-английски */
  englishName: string;
  /** Направление письма */
  dir: "ltr" | "rtl";
  /** Язык по умолчанию */
  default?: boolean;
  /**
   * Эмодзи-флаг страны, ассоциированной с языком — только когда такая
   * привязка однозначна. Для региональных/безгосударственных языков
   * (курдский, якутский, уйгурский и т.п.) намеренно не указан — в UI для
   * них показывается нейтральная иконка-глобус вместо гадания с флагом.
   */
  flag?: string;
}
